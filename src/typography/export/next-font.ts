import { isVariable, supportsGreek } from "../engine/font-support";
import { assignedRoles, familyFor, systemFontLoads, type SystemFontLoad } from "../engine/system-fonts";
import type { FontDefinition, FontId, TypographySystem } from "../types";

function camelCase(id: string): string {
  return id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase()).replace(/^(\d)/, "_$1");
}

function quoteList(values: (string | number)[]): string {
  return `[${values.map((v) => `"${v}"`).join(", ")}]`;
}

/** next/font/google options for one font, honouring static vs variable rules. */
function loaderOptions(load: SystemFontLoad): string[] {
  const { font } = load;
  const lines: string[] = [];
  if (!isVariable(font)) {
    const weights = load.weights.map(String);
    lines.push(`weight: ${weights.length === 1 ? `"${weights[0]}"` : quoteList(weights)},`);
  }
  if (load.styles.includes("italic")) lines.push(`style: ${quoteList(load.styles)},`);
  const subsets = supportsGreek(font) ? ["latin", "greek"] : ["latin"];
  lines.push(`subsets: ${quoteList(subsets)},`);
  if (load.axes.length && isVariable(font)) lines.push(`axes: ${quoteList(load.axes)},`);
  lines.push(`display: "swap",`);
  lines.push(`variable: "--font-${font.id}",`);
  return lines;
}

/** Fonts used as the primary of a stack that routes Greek glyphs to a companion. */
export function fontsNeedingFamilyOnly(system: TypographySystem): FontId[] {
  const ids = assignedRoles(system)
    .map((role) => familyFor(system, role))
    .filter((a) => a.greekCompanion)
    .map((a) => a.font);
  return [...new Set(ids)];
}

export function nextFontModule(system: TypographySystem): string {
  const loads = systemFontLoads(system);
  const familyOnly = fontsNeedingFamilyOnly(system);
  const imports = [...new Set(loads.map((l) => l.font.provider.importName))].sort();
  const header = [
    `// src/app/fonts.ts — ${system.id} ${system.name}`,
    `// Generated by the Typography Design Library. Fonts are self-hosted at build time by next/font.`,
    `// \`subsets\` only controls preloading; every subset stays available through unicode-range.`,
    `// For a Greek-first site preload ["greek"] (and "latin" only if Latin appears above the fold).`,
    `import { ${imports.join(", ")} } from "next/font/google";`,
    "",
  ];
  const blocks = loads.map((load) => {
    const name = camelCase(load.font.id);
    const role = [...load.roles, ...load.companionFor.map((r) => `${r} (Greek companion)`)].join(", ");
    return [
      `// ${load.font.family} — ${role}`,
      `export const ${name} = ${load.font.provider.importName}({`,
      ...loaderOptions(load).map((l) => `  ${l}`),
      `});`,
    ].join("\n");
  });
  const footer = [
    "",
    `/** Apply on <html>: defines every --font-* variable the typography CSS references. */`,
    `export const fontVariables = [${loads.map((l) => `${camelCase(l.font.id)}.variable`).join(", ")}].join(" ");`,
  ];
  if (familyOnly.length) {
    footer.push(
      "",
      `/**`,
      ` * --font-<id>-only: the bare family name of Latin-only fonts. next/font always adds a`,
      ` * metric-adjusted local fallback (Times New Roman / Arial) without unicode-range; it would`,
      ` * render Greek glyphs before the Greek companion. Render this once, e.g. in the root layout.`,
      ` */`,
      `const familyOnly = (font: { style: { fontFamily: string } }) => font.style.fontFamily.split(",")[0].trim();`,
      `export const fontOnlyCss = \`:root{${familyOnly.map((id) => `--font-${id}-only:\${familyOnly(${camelCase(id)})};`).join("")}}\`;`,
    );
  }
  return [...header, blocks.join("\n\n"), ...footer].join("\n") + "\n";
}

/** Stand-alone next/font loader for one family, with everything this library loads. */
export function fontLoaderSnippet(font: FontDefinition): string {
  const load: SystemFontLoad = {
    font,
    roles: [],
    companionFor: [],
    weights: font.weights,
    styles: font.styles,
    axes: font.loadedAxes,
  };
  const name = camelCase(font.id);
  return [
    `import { ${font.provider.importName} } from "next/font/google";`,
    "",
    `export const ${name} = ${font.provider.importName}({`,
    ...loaderOptions(load).map((l) => `  ${l}`),
    `});`,
    "",
    `// <html className={${name}.variable}> … then in CSS:`,
    `// font-family: var(--font-${font.id}), ${font.fallback};`,
  ].join("\n");
}

export function nextLayoutSnippet(system: TypographySystem, lang: "el" | "en" = "el"): string {
  const familyOnly = fontsNeedingFamilyOnly(system).length > 0;
  return `// src/app/layout.tsx — ${system.id} ${system.name}
import type { Metadata } from "next";
import { ${familyOnly ? "fontOnlyCss, fontVariables" : "fontVariables"} } from "./fonts";
import "./typography.css"; // the CSS from this contract (after your reset)

export const metadata: Metadata = { title: "…" };

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    // Set lang to the page language: "el" for Greek, "en" for English.
    <html lang="${lang}" className={fontVariables}>
      <body>
${
  familyOnly
    ? `        <style href="font-family-only" precedence="default">
          {fontOnlyCss}
        </style>
`
    : ""
}        {children}
      </body>
    </html>
  );
}
`;
}
